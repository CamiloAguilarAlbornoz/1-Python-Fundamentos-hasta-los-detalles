numbers = list(range(1, 200)) # Entrega un arreglo con todos los números del 1 al 99, el ultimo no lo toma en cuenta
print(numbers)

sentence = ' '.join(['Hola', 'Mundo', 'desde', 'un', 'join', 'besos']) # Crea el string con las palabras del array y agregando un espacio entre cada elemento
print(sentence)

total = sum(numbers) # Suma todos los números del arreglo numbers
print(total)

higher = max(numbers) # El numero mayor de la lista
print(higher)

less = min(numbers) # El numero menor de la lista
print(less)

size = len(numbers) # El tamaño del arreglo
print(size)