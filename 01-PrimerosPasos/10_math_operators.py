# Suma
print(2 + 2)

# Resta
print(4 - 2)

# Multiplicacion
print(4 * 2)

# División
print(15 / 3)

# Otras Operaciones

# Potencia
print(2 ** 3) # Es lo mismo que decir 2 a la 3, lo cual es 8

# Divisón sin decimal
print(5//4) # Da una división SIN decimales, o sea es 1

# Modulo
print(5 % 4 ) # Lo que sobra de una división, o sea el residuo

# Redondear : round()
print(round(3.1)) # Al ser menor de 3.5, lo redondea al número menor, o sea 3
print(round(3.5)) # Al ser mayor o igual a 3.5, lo redondea al número mayor, o sea 4

# Valor absoluto : abs()
print(abs(-100))