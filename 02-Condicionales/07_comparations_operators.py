'''
Igualdad: ==

'''
print(5 == 5)
print(5 == 3)
print('hello' == 'hello')
'''
Desigualdad: !=
'''
print(5 != 5)
print(5 != 3)
print('hello' != 'world')
'''
Mayor que: >
'''
print(7 > 5)
print(5 > 9)
'''
Menor que: <
'''
print(7 < 5)
print(5 < 9)
'''
Mayor o igual que: >=
'''
print(7 >= 5)
print(5 >= 9)
print(5 >= 5)
'''
Menor o igual que: <=
'''
print(7 <= 5)
print(5 <= 9)
print(5 <= 5)